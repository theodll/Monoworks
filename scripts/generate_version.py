#!/usr/bin/env python3
# Generates Version.h from the current Git checkout.
# Usage: python GenerateVersion.py --repo-root ../ --output Version.h

import argparse
import json
import os
import subprocess
from pathlib import Path


CI_BRANCH_VARIABLES = (
    "GITHUB_HEAD_REF",
    "GITHUB_REF_NAME",
    "CI_COMMIT_REF_NAME",
    "BUILD_SOURCEBRANCHNAME",
    "BRANCH_NAME",
    "GIT_BRANCH",
)


def RunGit( repoRoot, *arguments ):
    result = subprocess.run( [ "git", "-C", str( repoRoot ), *arguments ], capture_output = True, text = True )

    if result.returncode != 0:
        return ""

    return result.stdout.strip()


def GetCommitHash( repoRoot ):
    commitHash = RunGit( repoRoot, "rev-parse", "HEAD" ).lower()

    if commitHash == "":
        return "unknown"

    return commitHash


def GetBranch( repoRoot ):
    branch = RunGit( repoRoot, "symbolic-ref", "--quiet", "--short", "HEAD" )

    if branch != "":
        return branch

    # Detached HEAD (typical on CI): fall back to CI-provided branch name
    for name in CI_BRANCH_VARIABLES:
        value = os.environ.get( name, "" ).strip()

        if value != "":
            return value

    return "DETACHED"


def CppString( value ):
    return json.dumps( value, ensure_ascii = False )


def RenderHeader( commitHash, branch ):
    shortHash = commitHash[ :12 ]

    return f'''// Generated by generate_version.py - do not edit.
#pragma once

#define MW_GIT_COMMIT_HASH {CppString( commitHash )}
#define MW_GIT_COMMIT_HASH_SHORT {CppString( shortHash )}
#define MW_GIT_BRANCH {CppString( branch )}

#if defined( __cplusplus )
    #include <string_view>

namespace Monoworks
{{
    inline constexpr std::string_view c_GitCommitHash{{ MW_GIT_COMMIT_HASH }};
    inline constexpr std::string_view c_GitCommitHashShort{{ MW_GIT_COMMIT_HASH_SHORT }};
    inline constexpr std::string_view c_GitBranch{{ MW_GIT_BRANCH }};
}}
#endif
'''


def WriteIfChanged( outputPath, content ):
    if outputPath.is_file() and outputPath.read_text( encoding = "utf-8" ) == content:
        return False

    outputPath.parent.mkdir( parents = True, exist_ok = True )
    outputPath.write_text( content, encoding = "utf-8" )

    return True


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument( "--repo-root", type = Path, default = Path.cwd() )
    parser.add_argument( "--output", type = Path, required = True )
    parser.add_argument( "--quiet", action = "store_true" )
    options = parser.parse_args()

    commitHash = GetCommitHash( options.repo_root )
    branch = GetBranch( options.repo_root )

    changed = WriteIfChanged( options.output, RenderHeader( commitHash, branch ) )

    if not options.quiet:
        state = "updated" if changed else "unchanged"
        print( f"[Version] {state}: {commitHash[ :12 ]} | Branch: {branch}" )


if __name__ == "__main__":
    main()